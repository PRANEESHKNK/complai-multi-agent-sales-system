
from agents import Agent, ModelSettings
from complai.email_tools import send_email_tool


MANAGER_INSTRUCTIONS = """
You are a Sales Manager at ComplAI.

You will receive three sales email drafts generated by different AI agents.

Your responsibilities:

1. Compare all three drafts.
2. Evaluate relevance, clarity, professionalism,
   credibility, and likelihood of receiving a response.
3. Do not invent customer facts or product capabilities.
4. Select the strongest draft.
5. Explain why you selected it.
6. Use the email tool exactly once.

Never claim an email was sent unless the tool confirms submission.
"""


def build_sales_manager(manager_model):

    return Agent(
        name="Sales Manager",
        instructions=MANAGER_INSTRUCTIONS,
        tools=[send_email_tool],
        model=manager_model,
        model_settings=ModelSettings(max_tokens=2048),
    )
